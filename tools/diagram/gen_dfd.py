def risk(p, code, x, y, attach=None, w=200, h=58):
    p.note(code, R[code], x, y, w, h, kind="risk", attach=attach)


def ctrl(p, code, x, y, attach=None, w=200, h=58):
    p.note(code, C[code], x, y, w, h, kind="control", attach=attach)


def header(p, title, tobe):
    p.title(("TO-BE: " if tobe else "AS-IS: ") + title)
    p.text("<i>Медикаменте · DFD уровня 1 · нотация Gane-Sarson · "
           + ("меры защиты C-xx (05-controls.md)" if tobe else "проблемные зоны R-xx (02-security-audit.md)")
           + "</i>", 20, 40, 900, 20)


def build(name, title, fn, level0=False):
    d = Diagram()
    for tobe in (False, True):
        p = d.page("to-be" if tobe else "as-is")
        p.title(("TO-BE: " if tobe else "AS-IS: ") + title)
        p.text("<i>Медикаменте · " + ("контекстная диаграмма (уровень 0)" if level0 else "DFD уровня 1")
               + " · нотация Gane-Sarson · "
               + ("меры защиты C-xx (05-controls.md)" if tobe else "проблемные зоны R-xx (02-security-audit.md)")
               + "</i>", 20, 40, 900, 20)
        fn(p, tobe)
    path = os.path.join(OUT, name + ".drawio")
    d.write(path)
    print(path)


